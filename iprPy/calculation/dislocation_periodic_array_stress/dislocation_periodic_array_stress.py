import datetime
from typing import Optional, Union

# http://www.numpy.org/
import numpy as np

# https://github.com/usnistgov/atomman 
import atomman as am
import atomman.unitconvert as uc
from atomman.typing import lammpspotential, unitfloat
from atomman.lammps import LAMMPS, LAMMPSobj

def dislocation_periodic_array_stress(lammps_command: Union[str, LAMMPSobj],
                                      system: am.System,
                                      potential: lammpspotential,
                                      temperature: float,
                                      mpi_command: Optional[str] = None,
                                      linesizemult: int = 1,
                                      sigma_screw: unitfloat = 0.0,
                                      sigma_edge: unitfloat = 0.0,
                                      thermosteps: int = 100,
                                      dumpsteps: Optional[int] = None,
                                      runsteps: int = 1000000,                                     
                                      rigidbounds: bool = True, 
                                      createvelocities: bool = True,
                                      randomseed: Optional[int] = None,
                                      usefiles: bool = False) -> dict:
    """
    Applies a constant external shear stress to the boundary atoms in a
    periodic array of dislocations configuration to evaluate the strain rate.

    Parameters
    ----------
    lammps_command : str, LAMMPSEXE or LAMMPSLIB
        LAMMPS executable command, LAMMPS library name, or an atomman LAMMPS
        interface object.
    system : atomman.System
        An atomic configuration of a periodic array of dislocations as generated
        by the dislocation_periodic_array calculation method.
    potential : PotentialLAMMPS or PotentialLAMMPSKIM
        The LAMMPS implemented potential to use.
    temperature : float
        The temperature to run the simulation at.
    mpi_command : str or None, optional
        The MPI command for running LAMMPS in parallel.  If not given, LAMMPS
        will run serially.
    linesizemult : int, optional
        Indicates how many times to replicate the initial configuration along
        the dislocation line direction prior to running the simulation.  This
        allows for easy exploration of multiple dislocation line lengths.
        Default value is 1 (i.e no extra replicas).
    sigma_screw : unitfloat, optional
        The shear stress to apply to the system that acts on the screw component
        of dislocations.  Default value is 0.0.
    sigma_edge: unitfloat, optional
        The shear stress to apply to the system that acts on the edge component
        of dislocations.  Default value is 0.0.
    thermosteps : int, optional
        How often to output thermo data.  Default value is 100 (timesteps).
    dumpsteps : int or None, optional
        How often to output atomic configurations as dump files.  Default value
        of None will set this to runsteps, i.e. only first and last
        configurations would be dumped.
    runsteps : int, optional
        The total number of MD steps to run.  Default value is 1,000,000.
    rigidbounds : bool, optional
        If True (default) the top and bottom boundary regions will be treated
        as rigid bodies.  If False, then the atoms in the boundaries will be
        allowed to relax but will still have the shear stress(es) applied to
        them.
    createvelocities : bool, optional
        If True (default), new random velocities will be assigned to the
        non-rigid atoms based on 2*temperature. Setting this to False will
        use any pre-assigned velocities to the atoms.
    randomseed : int or None, optional
        Random number seed used by LAMMPS.  Default is None which will select
        a random int between 1 and 900000000.
    usefiles : bool, optional
        False (default) minimizes the number of files generated by the
        calculation, while True will always create a LAMMPS log file, input
        script file, and initial data configuration file.
    """

    logfile = 'pad_stress_log.lammps'
    if usefiles:
        script = 'pad_stress.in'
    else:
        script = None

    # Create a LAMMPS object if needed
    lmp = LAMMPS(lammps_command, mpi_command=mpi_command, potential=potential)

    # Replicate along the line direction
    if linesizemult > 1:
        system = system.supersize(linesizemult, 1, 1)
        system.pbc[2] = False

    # Check/select the randomseed
    randomseed = am.lammps.seed(randomseed)

    # Set default timestep and dependent variables
    timestep = am.lammps.style.timestep(lmp.potential.units)
    temperature_damp = 100 * timestep

    # Pass system and potential info into LAMMPS
    lmp.new_system_from_data_file(system, filename='init.dat', tilt_large=True,
                                  logfile=logfile)

    lmp.commands_string('\n# Split system into top and bottom halves')
    lmp.cmd.region('top', 'block', 'INF', 'INF', 'INF', 'INF', '0', 'INF')
    lmp.cmd.region('bot', 'block', 'INF', 'INF', 'INF', 'INF', 'INF', '0')

    lmp.commands_string('\n# Separate atoms into move and boundary groups')
    move_atypes = [i for i in range(1, system.natypes // 2 + 1)]
    lmp.cmd.group('move', 'type', *move_atypes)
    lmp.cmd.group('boundary', 'subtract', 'all', 'move')
    lmp.cmd.group('top', 'region', 'top')
    lmp.cmd.group('bot', 'region', 'bot')

    if createvelocities:
        lmp.commands_string('\n# Create velocities')
        if rigidbounds:
            lmp.cmd.velocity('move', 'create', 2*temperature, randomseed,
                            'mom', 'yes', 'rot', 'yes', 'dist', 'gaussian')
        else:
            lmp.cmd.velocity('all', 'create', 2*temperature, randomseed,
                            'mom', 'yes', 'rot', 'yes', 'dist', 'gaussian')

    lmp.commands_string('\n# Find top and bottom boundary atoms')
    lmp.cmd.group('topboundary', 'intersect', 'boundary', 'top')
    lmp.cmd.group('botboundary', 'intersect', 'boundary', 'bot')

    lmp.commands_string('\n# Extract important values')
    lmp.cmd.variable('area', 'equal', 'lx*ly')
    lmp.cmd.variable('lz', 'equal', 'lz')
    lmp.cmd.variable('ntop', 'equal', 'count(topboundary)')
    lmp.cmd.variable('nbot', 'equal', 'count(botboundary)')

    lmp.commands_string('\n# Compute the forces for the shear stresses')
    lammps_stress_units = f'{lmp.unitsdict["force"]}/{lmp.unitsdict["length"]}^2'
    lmp.cmd.variable('sigma_screw', 'equal', uc.get_in_units(sigma_screw, lammps_stress_units))
    lmp.cmd.variable('sigma_edge', 'equal', uc.get_in_units(sigma_edge, lammps_stress_units))
    lmp.cmd.variable('fx', 'equal', '${sigma_screw}*${area}/(${ntop}+${nbot})')
    lmp.cmd.variable('fy', 'equal', '${sigma_edge}*${area}/(${ntop}+${nbot})')

    lmp.commands_string('\n# Calculate strains')
    lmp.cmd.compute('displacement', 'all', 'displace/atom')
    lmp.cmd.compute('disptopx', 'topboundary', 'reduce', 'ave', 'c_displacement[1]')
    lmp.cmd.compute('disptopy', 'topboundary', 'reduce', 'ave', 'c_displacement[2]')
    lmp.cmd.compute('dispbotx', 'botboundary', 'reduce', 'ave', 'c_displacement[1]')
    lmp.cmd.compute('dispboty', 'botboundary', 'reduce', 'ave', 'c_displacement[2]')
    lmp.cmd.variable('strain_xz', 'equal', '(c_disptopx-c_dispbotx)/${lz}')
    lmp.cmd.variable('strain_yz', 'equal', '(c_disptopy-c_dispboty)/${lz}')

    lmp.commands_string('\n# Define integrator')
    lmp.cmd.timestep(timestep)
    if rigidbounds:
        lmp.cmd.fix('nvt', 'move', 'nvt', 'temp', temperature, temperature, temperature_damp)
        lmp.cmd.fix('nvtboundary', 'boundary', 'rigid/nvt', 'group', 2, 'topboundary', 'botboundary', 'temp', temperature, temperature, temperature_damp)
        lmp.cmd.neigh_modify('exclude', 'group', 'topboundary', 'topboundary')
        lmp.cmd.neigh_modify('exclude', 'group', 'botboundary', 'botboundary')
    else:
        lmp.cmd.fix('nvt', 'all', 'nvt', 'temp', temperature, temperature, temperature_damp)

    lmp.commands_string('\n# Apply the external stress to the boundary atoms')
    lmp.cmd.fix('ftop', 'topboundary', 'addforce', '${fx}', '${fy}', '0.0')
    lmp.cmd.fix('fbot', 'botboundary', 'addforce', '-${fx}', '-${fy}', '0.0')

    lmp.commands_string('\n# Define the thermo output')
    lmp.cmd.thermo(thermosteps)
    lmp.cmd.thermo_style('custom', 'step', 'temp', 'etotal', 'v_strain_xz', 'v_strain_yz')
    lmp.cmd.thermo_modify('format', 'float', '%.16f')

    lmp.commands_string('\n# Define the dump output')
    lmp.cmd.dump('dumpy', 'all', 'custom', dumpsteps, '*.dump', 'id', 'type', 'x', 'y', 'z', 'vx', 'vy', 'vz', 'fx', 'fy', 'fz')


    lmp.commands_string('\n# Run MD')
    lmp.cmd.run(runsteps)

    # Run EXE, get log output
    log = lmp.end_and_get_log(script)

    thermo = log.simulations[0].thermo

    return {'thermo':thermo}